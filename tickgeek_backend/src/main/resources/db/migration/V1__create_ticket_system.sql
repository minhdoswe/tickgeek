-- Schema for requesting an email sign-in code (specs/001-request-code/data-model.md).
-- Flyway runs this file in one transaction, so no BEGIN/COMMIT here.

-- Enum types
CREATE TYPE outbox_status AS ENUM (
    'PENDING', 'SENT', 'ERROR', 'CANCELLED'
);

-- Verification codes: tied to an email, not a user, so new people can get one.
CREATE TABLE verification_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    code_hmac TEXT NOT NULL,
    status TEXT NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    request_source TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    used_at TIMESTAMPTZ,

    CONSTRAINT verification_codes_status_check
        CHECK (status IN ('PENDING', 'ACTIVE', 'USED', 'INVALIDATED')),
    CONSTRAINT verification_codes_attempt_count_check
        CHECK (attempt_count BETWEEN 0 AND 5),
    CONSTRAINT verification_codes_active_expiry_check
        CHECK (status <> 'ACTIVE' OR expires_at IS NOT NULL)
);

-- Outboxes: code emails link to their code; payloads are erased once a job finishes.
CREATE TABLE outboxes (
    id UUID PRIMARY KEY,
    payload TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ,
    attempts INT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error TEXT,
    status outbox_status NOT NULL,
    verification_code_id BIGINT REFERENCES verification_codes (id)
);

-- Indexes
CREATE UNIQUE INDEX verification_codes_one_live_per_email_idx
    ON verification_codes (email) WHERE status IN ('PENDING', 'ACTIVE');
CREATE INDEX verification_codes_email_created_at_idx
    ON verification_codes (email, created_at);
CREATE INDEX verification_codes_source_created_at_idx
    ON verification_codes (request_source, created_at);
CREATE INDEX verification_codes_created_at_idx
    ON verification_codes (created_at);

